class Destination {
  final String name;
  final String description;
  final String location;
  final String image;
  final String price;
  final double rating;
  final int guest;
  final int km;
  final int minute;

  Destination({
    required this.name,
    required this.description,
    required this.location,
    required this.image,
    required this.price,
    required this.rating,
    required this.guest,
    required this.km,
    required this.minute,
  });
}